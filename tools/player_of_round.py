"""Build the homepage 'Player of the round' data from a match stats CSV.

Usage:
  python3 tools/player_of_round.py path/to/round-match-stats.csv \
      --label "Grand Final 2026" --result "Brisbane 14.12 (96) d Fremantle 12.17 (89)" --where "MCG, 26 September 2026"

Writes assets/data/player-of-the-round.js. The player of the round is the player with the most rating points
(the RatingPoints column), unless --player names someone else.
"""
import csv, json, argparse, os
ap = argparse.ArgumentParser()
ap.add_argument('csv'); ap.add_argument('--label', required=True); ap.add_argument('--result', required=True)
ap.add_argument('--where', default=''); ap.add_argument('--player', default='')
ap.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..', 'assets', 'data', 'player-of-the-round.js'))
a = ap.parse_args()
COLS = ['Rating_Q1', 'Rating_Q2', 'Rating_Q3', 'Rating_Q4', 'RatingPoints', 'Equity_PreClearance', 'Equity_PostClearance', 'Equity_Possession',
        'Equity_BallUse', 'Disposals', 'Kicks', 'Handballs', 'MetresGained', 'Inside50s', 'Tackles', 'PressureActs', 'ContestedPossessions',
        'Intercepts', 'Marks', 'ContestedMarks', 'TotalClearances', 'Hitouts', 'HitoutsToAdvantage', 'Goals', 'Behinds', 'ScoreInvolvements',
        'GoalAssists', 'CentreBounceAttendancePercentage', 'TimeOnGround', 'DisposalEfficiency']
rows = [r for r in csv.DictReader(open(a.csv, encoding='utf-8-sig')) if r.get('Player')]
num = lambda v: float(v) if v not in ('', None) else 0.0
players = [[r['Player'], r['Team']] + [num(r[c]) for c in COLS] for r in rows]
players.sort(key=lambda p: -p[2 + COLS.index('RatingPoints')])
pick = next((p for p in players if p[0] == a.player), players[0]) if a.player else players[0]
# Publish only what the homepage card shows: the pick's name, team and rating points.
# The full match table stays in the CSV, which is not deployed.
data = {'label': a.label, 'result': a.result, 'where': a.where, 'cols': ['RatingPoints'], 'player': pick[0],
        'players': [[pick[0], pick[1], pick[2 + COLS.index('RatingPoints')]]], 'source': os.path.basename(a.csv)}
open(a.out, 'w', encoding='utf-8').write('/* generated by tools/player_of_round.py from ' + os.path.basename(a.csv) + ' */\nwindow.DAM_POTR=' + json.dumps(data, separators=(',', ':')) + ';\n')
print('player of the round:', pick[0], pick[1], pick[2 + COLS.index('RatingPoints')], '->', a.out)
